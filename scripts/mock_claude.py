"""A stand-in for `claude -p` that answers from the prompt alone.

Selected with ``ROBUSTO_BACKEND=mock`` or ``--backend mock``. It makes no model
call and spends no tokens. Everything else in the pipeline runs for real: the
deterministic parse, prompt rendering, the schema contract, JSON recovery,
validation, the bounded retry, normalisation, editor-input assembly, and the
final-report check. That is the whole point: those stages can be exercised end
to end, on a real manuscript, before a single reviewer token is spent, and in CI
where no CLI is logged in.

The mock decides what it is being asked from the prompt text on stdin, the same
way the model would:

    probe      the environment check's nonce, echoed back
    reviewer   ``- reviewer = "..."`` plus an inlined output contract
    selector   ``Act as the reviewer_applicability_router``
    editor     ``Act as the editor for this run``

A reviewer reply is a synthetic but fully valid JSON object: real finding ids in
the reviewer's prefix, a source object pointing at a file that exists under the
run's ``parsed/`` directory, a ``cannot_verify`` finding to exercise that route,
copyedit findings from the grammar auditor so the editor must produce the
grammar appendix, and a medium-severity parser finding from the preflight
auditor so the warning path fires without blocking.

Two knobs exist to exercise the paths that only misbehaviour reaches:

    ROBUSTO_MOCK_DRIFT=name[,name]   first reply breaks the contract, the retry
                                     succeeds
    ROBUSTO_MOCK_FAIL=name[,name]    every reply breaks the contract, so the
                                     reviewer fails loudly after one retry

And two to shape the run:

    ROBUSTO_MOCK_FINDINGS=N          findings per reviewer (default 2)
    ROBUSTO_MOCK_SKIP=name[,name]    optional reviewers the selector skips

Every synthetic artifact says so on its face. The report opens with a banner,
each finding summary names the mock, and the run manifest records the backend,
so nothing produced here can pass for a review.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import sys
from pathlib import Path

PROBE_TOKEN = "robusto-probe-ok"
RETRY_MARKER = "did not satisfy the output contract"
CONTRACT_MARKER = "# Output contract"
EDITOR_MARKER = "Act as the editor for this run"
SELECTOR_MARKER = "Act as the reviewer_applicability_router"

MOCK_NOTE = "Generated by the robusto mock backend; synthetic, not a review."


def env_names(name: str) -> set[str]:
    return {item.strip() for item in os.environ.get(name, "").split(",") if item.strip()}


def env_int(name: str, default: int) -> int:
    try:
        return int(os.environ.get(name, "") or default)
    except ValueError:
        return default


def first(pattern: str, text: str) -> str | None:
    match = re.search(pattern, text)
    return match.group(1) if match else None


def json_blocks(text: str) -> list[object]:
    """Every fenced JSON block that parses, in order."""
    found = []
    for match in re.finditer(r"```json\s*(.*?)\s*```", text, re.S):
        try:
            found.append(json.loads(match.group(1)))
        except ValueError:
            continue
    return found


def fenced_by_name(name: str) -> bool:
    """Deterministically vary reply shape so both recovery paths get exercised."""
    return int(hashlib.sha1(name.encode()).hexdigest(), 16) % 2 == 0


def emit(payload: dict, *, fenced: bool, broken: bool) -> None:
    body = json.dumps(payload, indent=2, ensure_ascii=False)
    if broken:
        # Prose either side, a fence, and a required field missing: enough to
        # fail the schema, so the retry path has something to correct.
        sys.stdout.write("Here is my assessment of the manuscript.\n\n")
        sys.stdout.write("```json\n" + body + "\n```\n\nLet me know if you need more.\n")
        return
    if fenced:
        sys.stdout.write("```json\n" + body + "\n```\n")
    else:
        sys.stdout.write(body + "\n")


