def editor_reply(prompt: str) -> int:
    paper_id = first(r'Produce the final markdown report for paper_id "([^"]+)"', prompt)
    if not paper_id:
        print("mock: could not read paper_id from the editor prompt", file=sys.stderr)
        return 2
    bundle_path = Path("work") / paper_id / "editor" / "normalized_bundle.json"
    try:
        bundle = json.loads(bundle_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"mock: could not read {bundle_path}: {exc}", file=sys.stderr)
        return 2

    canonical = [item for item in bundle.get("canonical_findings", []) if isinstance(item, dict)]
    has_copyedit = any(item.get("issue_class") == "copyedit_issue" for item in canonical)

    # Identifiers may appear only in the traceability appendix, so the body
    # below never prints one.
    lines = [
        "# Multi-Agent Paper Review Report",
        "",
        "**MOCK BACKEND. This is not a review of the manuscript.** Every finding "
        "below is synthetic, generated without reading the paper, so that the "
        "pipeline's assembly, validation and reporting stages could be exercised "
        "without spending model tokens. Discard it once the machinery is proven.",
        "",
        "## Executive Summary",
        "",
        f"This run processed paper `{paper_id}` through the full multi-agent "
        "pipeline with a mock backend standing in for every model call. The "
        "deterministic parse, prompt rendering, schema contract, JSON recovery, "
        "validation, normalisation and editor assembly all ran for real; only the "
        "content of each finding is fabricated. The report therefore says nothing "
        "about the manuscript and everything about whether the pipeline works.",
        "",
        f"The normalised bundle holds {len(canonical)} canonical finding(s). Three "
        "synthetic corrections are listed below purely to populate the required "
        "sections in the shape the real editor uses.",
        "",
        "## Highest-Priority Cross-Agent Findings",
        "",
    ]
    for number in range(1, 4):
        lines += [
            f"### {number}. Synthetic headline finding {number}",
            "",
            "**Evidence.** None was examined. The mock backend fabricates findings "
            "of the correct shape so that each downstream stage receives input.",
            "",
            "**Why it matters.** It does not. The value of this run is that every "
            "stage after the model call executed and validated.",
            "",
            "**Minimum adequate correction.** None. Delete this report once the "
            "real backend has produced a genuine one.",
            "",
        ]
    lines += [
        "## Suggested Revision Priorities",
        "",
        "1. Log the Claude Code CLI in and rerun with the real backend.",
        "2. Read the genuine report that run produces.",
        "3. Treat nothing in this document as a statement about the manuscript.",
        "",
        "## Additional Findings",
        "",
        "### Material Qualifications",
        "",
        "| Area | Location | Issue | Suggested revision |",
        "|---|---|---|---|",
        "| Mock | Mock section | Synthetic qualification generated by the mock backend | None |",
        "",
        "### Exploratory Interpretation and Development",
        "",
        "| Area | Location | Issue | Suggested revision |",
        "|---|---|---|---|",
        "| Mock | Mock section | Synthetic exploratory item generated by the mock backend | None |",
        "",
        "## Items Marked Cannot Verify",
        "",
        "| Item | What is established | What remains unavailable | Proportionate next step |",
        "|---|---|---|---|",
        "| Synthetic cannot-verify items | Nothing; no evidence was examined | Everything | Run the real backend |",
        "",
    ]
    if has_copyedit:
        lines += [
            "## Appendix: Grammar and Copyediting Issues",
            "",
            "| Location | Current text | Issue | Suggested correction |",
            "|---|---|---|---|",
            "| Mock section | synthetic quotation from the mock backend | Synthetic copyedit item | None |",
            "",
        ]
    lines += [
        "## Appendix: Parser and Preprocessing Limitations",
        "",
        "The preflight auditor's synthetic medium-severity parser finding exists to "
        "exercise the warning path. It describes no real limitation of the parsed "
        "artifacts.",
        "",
        "## Appendix: Review Scope and Limitations",
        "",
        "No substantive domain was reviewed. A mock backend answered every model "
        "call with fabricated, schema-valid output. This appendix exists because "
        "the final-report check requires it, and it is accurate: the scope of this "
        "review is empty.",
        "",
        "## Appendix: Traceability Map",
        "",
        "| Report section | Finding | Canonical ID | Source finding IDs |",
        "|---|---|---|---|",
    ]
    for item in canonical:
        canonical_id = item.get("canonical_id") or ""
        sources = ", ".join(
            f"{source.get('reviewer')}:{source.get('id')}"
            for source in item.get("source_findings", [])
            if source.get("reviewer") and source.get("id")
        )
        summary = " ".join(str(item.get("finding_summary") or item.get("summary") or "Synthetic finding").split())
        summary = summary.replace("|", "/")[:80]
        lines.append(f"| Additional Findings | {summary} | {canonical_id} | {sources} |")
    lines.append("")

    sys.stdout.write("\n".join(lines))
    return 0


# --------------------------------------------------------------------------- #

def main() -> int:
    prompt = sys.stdin.read()
    if PROBE_TOKEN in prompt:
        sys.stdout.write(PROBE_TOKEN + "\n")
        return 0
    if EDITOR_MARKER in prompt:
        return editor_reply(prompt)
    if SELECTOR_MARKER in prompt:
        return selector_reply(prompt)
    if CONTRACT_MARKER in prompt:
        return reviewer_reply(prompt, is_retry=RETRY_MARKER in prompt)
    print("mock: unrecognised prompt; no marker found", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
