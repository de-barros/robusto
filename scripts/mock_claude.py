def selector_reply(prompt: str) -> int:
    paper_id = first(r'Classify paper_id "([^"]+)"', prompt)
    catalog = next((block for block in json_blocks(prompt) if isinstance(block, list)), None)
    if not paper_id or catalog is None:
        print("mock: could not read paper_id and the optional-reviewer catalog", file=sys.stderr)
        return 2
    skip = env_names("ROBUSTO_MOCK_SKIP")
    selected = []
    skipped = []
    for entry in catalog:
        name = entry.get("name") if isinstance(entry, dict) else None
        if not name:
            continue
        if name in skip:
            skipped.append({"name": name, "reason": "Skipped on request of ROBUSTO_MOCK_SKIP."})
        else:
            selected.append({"name": name, "reason": "The mock backend selects every conditional specialist."})
    payload = {
        "paper_id": paper_id,
        "paper_type": "empirical_causal",
        "selection_confidence": "high",
        "selection_mode": "applicability",
        "selected_optional_reviewers": selected,
        "skipped_optional_reviewers": skipped,
        "notes": [MOCK_NOTE],
    }
    emit(payload, fenced=False, broken=False)
    return 0


