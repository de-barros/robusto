def evidence_file(paper_id: str) -> str | None:
    """A repo-relative path to a real parsed artifact, forward slashes."""
    parsed = Path("work") / paper_id / "parsed"
    preferred = parsed / "full_text.md"
    if preferred.is_file():
        return preferred.as_posix()
    for candidate in sorted(parsed.glob("*")):
        if candidate.is_file():
            return candidate.as_posix()
    return None


def issue_type_for(reviewer: str) -> str:
    if reviewer == "grammar_auditor":
        return "copyedit_issue"
    if reviewer == "parser_quality_auditor":
        # medium severity: prints a warning, does not trip the preflight gate
        return "parser_artifact"
    return "manuscript_issue"


def verifiable_finding(prefix: str, index: int, reviewer: str, path: str | None) -> dict:
    fid = f"{prefix}-{index:03d}"
    source_id = f"{fid}-src-1"
    numeric_check = None
    if reviewer == "numerical_auditor":
        numeric_check = {
            "reported_value": "0.90",
            "expected_value": "0.90",
            "method": "mock recomputation",
            "inputs": ["synthetic"],
            "recomputation_notes": MOCK_NOTE,
        }
    sources = []
    links = []
    if path is not None:
        sources.append(
            {
                "id": source_id,
                "type": "parsed_artifact",
                "label": Path(path).name,
                "path": path,
                "page": None,
                "page_label": None,
                "section": None,
                "text_quote": f"synthetic quotation {index} for {reviewer}",
                "url": None,
            }
        )
        links.append(
            {
                "claim_text": f"Synthetic claim {index} from {reviewer}.",
                "source_object_ids": [source_id],
                "relation": "partial",
                "note": MOCK_NOTE,
            }
        )
    return {
        "id": fid,
        "category": "mock",
        "finding_summary": f"Mock finding {index} from {reviewer}. Synthetic, for pipeline exercise only.",
        "issue_type": issue_type_for(reviewer),
        "severity": "medium" if index == 1 else "low",
        "confidence": "medium",
        "location": {
            "page": None,
            "page_label": None,
            "section": f"Mock section {index}",
            "text_quote": f"synthetic quotation {index} for {reviewer}",
            "precision": "partial",
        },
        "claim_text": f"Synthetic claim {index} from {reviewer}.",
        "assessment": "partially",
        "cannot_verify_reason": None,
        "evidence_summary": "No evidence was examined. The mock backend fabricates a well-formed finding so downstream stages have input.",
        "source_objects": sources,
        "claim_evidence_links": links,
        "numeric_check": numeric_check,
        "suggested_fix": "None. This finding exists only to exercise the pipeline.",
    }


def cannot_verify_finding(prefix: str, index: int, reviewer: str) -> dict:
    fid = f"{prefix}-{index:03d}"
    return {
        "id": fid,
        "category": "mock",
        "finding_summary": f"Mock cannot-verify finding {index} from {reviewer}. Synthetic.",
        "issue_type": "cannot_verify",
        "severity": "low",
        "confidence": "low",
        "location": {
            "page": None,
            "page_label": None,
            "section": None,
            "text_quote": None,
            "precision": "missing",
        },
        "claim_text": f"Synthetic claim {index} from {reviewer} that the mock declines to verify.",
        "assessment": "cannot_verify",
        "cannot_verify_reason": "The mock backend examines no evidence, so it cannot verify anything.",
        "evidence_summary": "Not examined.",
        "source_objects": [],
        "claim_evidence_links": [],
        "numeric_check": None,
        "suggested_fix": "None.",
    }


def reviewer_reply(prompt: str, is_retry: bool) -> int:
    reviewer = first(r'- reviewer = "([^"]+)"', prompt)
    paper_id = first(r'- paper_id = "([^"]+)"', prompt)
    prefix = first(r"formatted ([A-Z]+)-001", prompt)
    if not (reviewer and paper_id and prefix):
        print("mock: could not read reviewer, paper_id and id prefix from the prompt", file=sys.stderr)
        return 2

    count = max(0, env_int("ROBUSTO_MOCK_FINDINGS", 2))
    path = evidence_file(paper_id)
    findings = []
    for index in range(1, count + 1):
        if index == count and count > 1:
            findings.append(cannot_verify_finding(prefix, index, reviewer))
        else:
            findings.append(verifiable_finding(prefix, index, reviewer, path))

    payload = {
        "reviewer": reviewer,
        "paper_id": paper_id,
        "run_status": "ok",
        "summary": f"{MOCK_NOTE} {len(findings)} synthetic finding(s) from {reviewer}.",
        "findings": findings,
        "notes": [MOCK_NOTE],
    }

    broken = reviewer in env_names("ROBUSTO_MOCK_FAIL") or (
        reviewer in env_names("ROBUSTO_MOCK_DRIFT") and not is_retry
    )
    if broken:
        payload.pop("run_status")
    emit(payload, fenced=fenced_by_name(reviewer), broken=broken)
    return 0


